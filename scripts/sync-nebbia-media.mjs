const outputRoot = path.resolve('public/projects');
const sourceManifestPath = path.resolve('src/projectMedia.ts');
const stagingRoot = path.join(outputRoot, `.media-sync-${Date.now()}`);
const mediaPattern = /<(?:img|video|source)\b[^>]*?\bsrc=["']([^"']+)["']/gi;
const supportedMedia = /\.(?:gif|jpe?g|mp4|png|webp)(?:\?|$)/i;

function filenameFor(url, usedNames) {
  const parsed = new URL(url);
  const vimeoId = parsed.pathname.match(/playback\/(\d+)\//)?.[1];
  const original = vimeoId ? `vimeo-${vimeoId}.mp4` : decodeURIComponent(path.basename(parsed.pathname));
  const extension = path.extname(original);
  const stem = path.basename(original, extension);
  let filename = original;
  let suffix = 2;

  while (usedNames.has(filename)) {
    filename = `${stem}-${suffix}${extension}`;
    suffix += 1;
  }

  usedNames.add(filename);
  return filename;
}

function extractMedia(html) {
  const media = [];
  const seen = new Set();

  for (const match of html.matchAll(mediaPattern)) {
    const url = match[1].trim().replaceAll('&amp;', '&');
    if (!supportedMedia.test(url) || url.includes('/themes/nebbia-theme/')) continue;
    if (seen.has(url)) continue;
    seen.add(url);
    media.push(url);
  }

  return media;
}

async function fetchOrThrow(url) {
  const response = await fetch(url, { redirect: 'follow' });
  if (!response.ok) throw new Error(`${response.status} ${response.statusText}: ${url}`);
  return response;
}

async function downloadProject(slug, pageUrl) {
  const html = await (await fetchOrThrow(pageUrl)).text();
  const mediaUrls = extractMedia(html);
  const projectDirectory = path.join(stagingRoot, slug);
  const usedNames = new Set();
  const entries = mediaUrls.map((url, index) => ({
    index,
    url,
    filename: filenameFor(url, usedNames),
    type: new URL(url).pathname.toLowerCase().endsWith('.mp4') ? 'video' : 'image',
  }));

  await mkdir(projectDirectory, { recursive: true });
  await Promise.all(entries.map(async ({ url, filename }) => {
    const response = await fetchOrThrow(url);
    const bytes = new Uint8Array(await response.arrayBuffer());
    await writeFile(path.join(projectDirectory, filename), bytes);
  }));

  await writeFile(
    path.join(projectDirectory, 'media.json'),
    `${JSON.stringify({ source: pageUrl, media: entries }, null, 2)}\n`,
    'utf8',
  );

  return { slug, pageUrl, media: entries };
}

async function writeSourceManifest(manifest) {
  const lines = [
    '// Generated by scripts/sync-nebbia-media.mjs. Do not edit by hand.',
    "export type ProjectMedia = { src: string; type: 'image' | 'video' };",
    '',
    'export const projectMedia: Record<string, ProjectMedia[]> = {',
  ];

  for (const project of manifest.projects) {
    lines.push(`  ${JSON.stringify(project.slug)}: [`);
    for (const item of project.media) {
      lines.push(`    { src: ${JSON.stringify(`/projects/${project.slug}/${item.filename}`)}, type: ${JSON.stringify(item.type)} },`);
    }
    lines.push('  ],');
  }

  lines.push('};', '');
  await writeFile(sourceManifestPath, lines.join('\n'), 'utf8');
}

async function main() {
  await mkdir(stagingRoot, { recursive: true });

  try {
    const manifest = [];
    for (const [slug, pageUrl] of projects) {
      const project = await downloadProject(slug, pageUrl);
      manifest.push(project);
      console.log(`${slug}: ${project.media.length} media`);
    }

    for (const [slug] of projects) {
      const destination = path.join(outputRoot, slug);
      await rm(destination, { recursive: true, force: true });
      await rename(path.join(stagingRoot, slug), destination);
    }

    const savedManifest = { syncedAt: new Date().toISOString(), projects: manifest };
    await writeFile(
      path.join(outputRoot, 'media-manifest.json'),
      `${JSON.stringify(savedManifest, null, 2)}\n`,
      'utf8',
    );
    await writeSourceManifest(savedManifest);
  } catch (error) {
    await rm(stagingRoot, { recursive: true, force: true });
    throw error;
  }

  await rm(stagingRoot, { recursive: true, force: true });
}

if (process.argv.includes('--manifest-only')) {
  const existing = JSON.parse(await readFile(path.join(outputRoot, 'media-manifest.json'), 'utf8'));
  await writeSourceManifest(existing);
} else {
  await main();
}
